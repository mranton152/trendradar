"""Обучающая выборка для этапа 1.

Заказчик дал 100 положительных примеров и ни одного отрицательного. Модель,
обученная только на положительных, не умеет ничего - ей не с чем сравнивать.
Отрицательные собираем сами: зрелые технологии, отраслевые стандарты,
массово внедрённые решения по тем же шести областям, поровну.

Два правила, оба ради честности:

1. Отрицательный без обоснования - это мнение, а не разметка. У каждого
   написано, почему он зрелый: сформированный рынок, выраженные лидеры,
   массовое внедрение - ровно те признаки, которыми ТЗ определяет
   "не слабый сигнал". Это же пойдёт на слайд.

2. Области поровну. Если отрицательные будут из других областей, чем
   положительные, классификатор выучит область вместо зрелости и покажет
   красивую точность ни о чём.
"""
import hashlib

import openpyxl

