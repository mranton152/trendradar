def _cand_id(label: str) -> str:
    return "ds:" + hashlib.sha1(label.lower().encode()).hexdigest()[:12]


def загрузить_положительные(xlsx: str) -> list[dict]:
    """100 строк заказчика. Колонки берём по заголовку второй строки листа."""
    ws = openpyxl.load_workbook(xlsx, read_only=True).worksheets[0]
    rows = list(ws.iter_rows(values_only=True))
    hdr = {h: i for i, h in enumerate(rows[1]) if h}
    out = []
    for r in rows[2:]:
        if not any(r):
            continue
        label = str(r[hdr["Технология (слабый сигнал)"]]).strip()
        out.append({
            "cand_id": _cand_id(label),
            "label": label,
            "domain": str(r[hdr["Область"]]).strip(),
            "companies": str(r[hdr["Компании"]] or ""),
            "why": str(r[hdr["Почему это слабый сигнал"]] or ""),
            "dataset_stage": str(r[hdr["Стадия развития"]] or ""),
            "dataset_trend": str(r[hdr["Тренд упоминаний"]] or ""),
            "dataset_score": int(r[hdr["Балл (стадия+тренд)"]]),
            "sources": str(r[hdr["Источники"]] or ""),
            "is_weak_signal": True,
        })
    return out


def _зрелые(область: str, пары: list[tuple[str, str]]) -> list[dict]:
    return [{"cand_id": _cand_id(имя), "label": имя, "domain": область, "why": почему,
             "why_mature": почему, "is_weak_signal": False} for имя, почему in пары]


