"""Промпт для извлечения фактов из документов, а не генерации знаний о тренде."""

from collections.abc import Mapping, Sequence
from typing import Any

TEMPLATE = """Ты описываешь технологию, но извлекаешь факты только из поданных документов.

Тренд: {label}
Год взлёта: {takeoff}. Публикаций за окно: {n_docs}. Стран: {n_countries}.

ДОКУМЕНТЫ:
{documents}

ДОПУСТИМЫЕ ID ДЛЯ ЦИТИРОВАНИЯ:
{allowed_doc_ids}

МАСШТАБ ДОКАЗАТЕЛЬСТВ:
{evidence_scope}

Составь карточку технологии «{label}» СТРОГО по этим документам. Верни только JSON:
{{
  "title_ru": "название тренда по-русски, 2-5 слов",
  "problem": "что это за технология и какую проблему она решает, 1-2 предложения",
  "problem_docs": ["doc_id, из которых это следует"],
  "advantage": "какое даёт преимущество, 1-2 предложения",
  "advantage_docs": ["doc_id"],
  "case_type": "research или company",
  "case_name": "название исследования или компании из документов",
  "case_text": "что именно они делают, 1-2 предложения",
  "case_docs": ["doc_id"]
}}

Правила:
- В `problem` и `advantage` описывай технологию «{label}», а не пересказывай
  отдельную статью. Обобщи общий механизм по всем документам.
- Если документы показывают применения в разных областях, назови общий механизм
  технологии, а не одну прикладную область. Не выдавай частный случай за суть технологии.
- `case_name` и `case_text` — один конкретный пример исследования или компании
  из поданных документов, а не обобщение.
- Если факта в документах нет — не пиши его. Пустая строка лучше выдумки.
- В `problem_docs`, `advantage_docs` и `case_docs` копируй ID только из блока
  «ДОПУСТИМЫЕ ID ДЛЯ ЦИТИРОВАНИЯ» буквально, включая все символы. Не используй
  название статьи, URL, порядковый номер или ID из своих знаний.
- Непустой `problem`, `advantage` или `case_text` обязан иметь хотя бы один ID
  в соответствующем поле `*_docs`. Если не можешь выбрать допустимый ID, верни
  пустую строку и пустой список для этой пары полей.
- Не используй знания вне поданных документов.
"""


def собрать(trend: Mapping[str, Any], documents: Sequence[Mapping[str, Any]]) -> str:
    """Готовит компактный, но достаточный контекст для LLM."""
    lines = []
    for document in documents:
        abstract = document.get("abstract")
        text = f"[{document['doc_id']}] ({document['year']}) {document['title']}"
        if isinstance(abstract, str) and abstract:
            text += f"\n  {abstract[:400]}"
        lines.append(text)

    if len(documents) == 1:
        evidence_scope = (
            "Подан РОВНО ОДИН документ. Нельзя обобщать свойства технологии в целом: "
            "описывай только задачу и результат этого конкретного исследования. "
            "`problem` обязан начинаться с «В единственном представленном исследовании», "
            "а `advantage` — с «В этом исследовании». Не пиши «технология "
            f"{trend['label']} позволяет» и не приписывай частный результат технологии в целом."
        )
    else:
        evidence_scope = (
            f"Количество документов: {len(documents)}. Синтезируй только общий механизм, "
            "который подтверждается несколькими документами. Не используй фразу "
            "«В единственном представленном исследовании»: она неверна для этого набора."
        )

    return TEMPLATE.format(
        label=trend["label"],
        takeoff=trend.get("takeoff_year"),
        n_docs=trend["n_docs"],
        n_countries=trend["n_countries"],
        documents="\n".join(lines) or "Документы для тренда не найдены.",
        allowed_doc_ids=", ".join(document["doc_id"] for document in documents) or "нет",
        evidence_scope=evidence_scope,
    )
