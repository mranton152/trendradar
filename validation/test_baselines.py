from validation.baselines import топ_по_cagr, топ_по_абсолютному_приросту

РЯДЫ = {
    "мейнстрим": {2018: 1000, 2021: 3000},   # +2000 в абсолюте
    "слабый":    {2018: 10, 2021: 200},      # x20 в процентах
    "мёртвый":   {2018: 500, 2021: 400},
    "малыш":     {2018: 1, 2021: 40},        # база меньше 5 — статистический шум
}


def test_абсолютный_прирост_поднимает_мейнстрим():
    """Ровно то, чем плох наивный baseline: он всегда выдаёт крупное."""
    assert топ_по_абсолютному_приросту(РЯДЫ, as_of=2021, k=1) == ["мейнстрим"]


def test_cagr_поднимает_слабый_сигнал():
    assert топ_по_cagr(РЯДЫ, as_of=2021, k=1) == ["слабый"]


def test_cagr_не_доверяет_микроскопической_базе():
    """Рост с одной публикации до сорока — это не тренд, это шум."""
    assert "малыш" not in топ_по_cagr(РЯДЫ, as_of=2021, k=3)
