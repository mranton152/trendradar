"""Базовые методы для сравнения.

Без них непонятно, что даёт наша модель. Эти два baseline выбраны намеренно:
они воспроизводят два самых частых способа «найти тренды», и оба провальны
по-своему — абсолютный прирост всегда поднимает крупное, CAGR всегда поднимает
шум с микроскопической базы.
"""

МИНИМАЛЬНАЯ_БАЗА = 5   # ниже этого рост в процентах ничего не значит
ОКНО = 3


def топ_по_абсолютному_приросту(ряды: dict[str, dict[int, int]], as_of: int,
                                k: int = 15) -> list[str]:
    """«Наивный рост»: на сколько документов выросло за окно."""
    прирост = {c: s.get(as_of, 0) - s.get(as_of - ОКНО, 0) for c, s in ряды.items()}
    return sorted(прирост, key=lambda c: прирост[c], reverse=True)[:k]


def топ_по_cagr(ряды: dict[str, dict[int, int]], as_of: int,
                k: int = 15) -> list[str]:
    """«Наивный процент»: среднегодовой темп роста за окно."""
    def cagr(s: dict[int, int]) -> float:
        было, стало = s.get(as_of - ОКНО, 0), s.get(as_of, 0)
        if было < МИНИМАЛЬНАЯ_БАЗА or стало <= 0:
            return 0.0
        return (стало / было) ** (1 / ОКНО) - 1

    подходящие = [c for c in ряды if cagr(ряды[c]) > 0]
    return sorted(подходящие, key=lambda c: cagr(ряды[c]), reverse=True)[:k]
