"""Разделение жизней термина: старый тёзка против нынешней технологии.

Измерено на реальных данных: «diffusion model» в журналах взлетает в 2005 —
это физика диффузии, а не генеративные модели. «State space model» взлетает
там же — это теория управления. Строка одна, тем две.

Последствие серьёзнее, чем неверная подпись: год взлёта считается по первой
жизни термина, возраст выходит за порог MAX_AGE, и фильтр выбрасывает тренд
как «слишком старый». То есть метод теряет ровно те сигналы, ради которых
делается.

Здесь лечится дешёвая половина задачи — по форме ряда. Если между всплесками
лежит длинный провал, это почти наверняка разные темы, и считать надо по
последней. Настоящее разрешение смысла требует эмбеддингов контекста
(появятся вместе с candidates.parquet) — тогда эта эвристика станет
подстраховкой, а не основным инструментом.
"""

ПОРОГ_АКТИВНОСТИ = 5   # ниже — единичные срабатывания: OCR, ошибки метаданных
МАКС_РАЗРЫВ = 3        # год-два тишины наука допускает и внутри одной темы


def сегменты_активности(counts: dict[int, int],
                        порог: int = ПОРОГ_АКТИВНОСТИ,
                        макс_разрыв: int = МАКС_РАЗРЫВ) -> list[list[int]]:
    """Годы с заметной активностью, сгруппированные в непрерывные периоды.

    Два соседних активных года попадают в один сегмент, если между ними
    не больше `макс_разрыв` лет тишины.
    """
    активные = sorted(y for y, c in counts.items() if c >= порог)
    if not активные:
        return []

    сегменты, текущий = [], [активные[0]]
    for год in активные[1:]:
        if год - текущий[-1] <= макс_разрыв:
            текущий.append(год)
        else:
            сегменты.append(текущий)
            текущий = [год]
    сегменты.append(текущий)
    return сегменты


def текущий_сегмент(counts: dict[int, int], as_of: int,
                    порог: int = ПОРОГ_АКТИВНОСТИ,
                    макс_разрыв: int = МАКС_РАЗРЫВ) -> dict[int, int]:
    """Ряд последней жизни термина на момент среза.

    В режиме бэктеста берётся сегмент, актуальный на тот год, а не сегодняшний:
    иначе расчёт на срезе 2021 подсматривал бы в будущее.
    """
    история = {y: c for y, c in counts.items() if y <= as_of}
    сегменты = сегменты_активности(история, порог, макс_разрыв)
    if not сегменты:
        return история
    последний = сегменты[-1]
    return {y: c for y, c in история.items()
            if последний[0] <= y <= последний[-1]}


def есть_подозрение_на_тёзку(counts: dict[int, int], as_of: int) -> bool:
    """Больше одного сегмента до среза — у термина была прошлая жизнь.

    Это подозрение, а не приговор: тема могла заглохнуть и возродиться.
    Показываем как флаг доверия, а не как причину отбраковки.
    """
    история = {y: c for y, c in counts.items() if y <= as_of}
    return len(сегменты_активности(история)) > 1
