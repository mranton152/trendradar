from core.homonym import сегменты_активности, текущий_сегмент


def test_непрерывный_ряд_это_один_сегмент():
    counts = {2018: 10, 2019: 20, 2020: 40, 2021: 80}
    assert сегменты_активности(counts) == [[2018, 2019, 2020, 2021]]


def test_старый_тёзка_отделяется_разрывом():
    """Реальный случай: 'diffusion model' взлетает в 2005 из-за физики диффузии,
    а как технология рождается в 2020. Между ними — провал в полтора десятка лет."""
    counts = {2003: 40, 2004: 55, 2005: 60, 2006: 30,
              2019: 20, 2020: 90, 2021: 300}
    сегменты = сегменты_активности(counts)
    assert len(сегменты) == 2
    assert сегменты[0] == [2003, 2004, 2005, 2006]
    assert сегменты[1] == [2019, 2020, 2021]


def test_текущий_сегмент_это_последний():
    counts = {2003: 40, 2004: 55, 2019: 20, 2020: 90, 2021: 300}
    assert текущий_сегмент(counts, as_of=2021) == {2019: 20, 2020: 90, 2021: 300}


def test_единичные_срабатывания_не_образуют_сегмент():
    """Один-два документа 20-летней давности — это OCR и ошибки метаданных,
    а не отдельная жизнь термина."""
    counts = {2003: 1, 2004: 2, 2019: 20, 2020: 90}
    assert сегменты_активности(counts) == [[2019, 2020]]


def test_короткий_провал_не_разрывает_ряд():
    """Наука не публикует равномерно; год-два тишины — это шум, а не другая тема."""
    counts = {2017: 10, 2018: 12, 2020: 15, 2021: 40}
    assert len(сегменты_активности(counts)) == 1


def test_срез_в_прошлом_берёт_сегмент_того_времени():
    counts = {2003: 40, 2004: 55, 2019: 20, 2020: 90, 2021: 300}
    assert текущий_сегмент(counts, as_of=2005) == {2003: 40, 2004: 55}


def test_пустой_ряд_не_ломает_разбиение():
    assert сегменты_активности({}) == []
    assert текущий_сегмент({}, as_of=2026) == {}
