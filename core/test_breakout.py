"""Излом собственного тренда: старый смысл никуда не делся, но появился новый.

Ряды настоящие, выгружены из OpenAlex 09.09.2026 с фильтром по концепту
Artificial intelligence (C154945302) — то есть ровно так, как их видит наш
конвейер. Это не выдуманные числа: на них видно, что разрыва между жизнями
термина нет, а есть скачок относительно его же многолетнего уровня.
"""
from core.breakout import год_прорыва

# теория управления публикуется непрерывно, Mamba даёт скачок в 2025
SSM = {2014: 354, 2015: 344, 2016: 364, 2017: 374, 2018: 400, 2019: 445,
       2020: 502, 2021: 491, 2022: 423, 2023: 475, 2024: 534, 2025: 1166,
       2026: 1349}

# физика диффузии как фон, генеративные модели взлетают в 2023
DIFFUSION = {2014: 152, 2015: 131, 2016: 173, 2017: 126, 2018: 151, 2019: 182,
             2020: 202, 2021: 236, 2022: 209, 2023: 502, 2024: 1452,
             2025: 3316, 2026: 3428}

# ровно растущий мейнстрим без второй жизни
МЕЙНСТРИМ = {y: 1000 + (y - 2014) * 120 for y in range(2014, 2027)}

# молодой термин: до окна поиска его просто не было
МОЛОДОЙ = {2022: 8, 2023: 60, 2024: 240, 2025: 700, 2026: 1100}


def test_ssm_ловится_на_скачке_2025():
    """Без этого взлёт SSM = 2005, возраст 21 год, и Mamba выпадает из выдачи —
    хотя стоит в нашем же эталонном списке того, что метод обязан находить."""
    assert год_прорыва(SSM, as_of=2026) == 2025


def test_diffusion_ловится_на_скачке_2023():
    assert год_прорыва(DIFFUSION, as_of=2026) == 2023


def test_ровный_мейнстрим_не_считается_второй_жизнью():
    """Иначе метод начнёт вытаскивать наверх крупное и давно известное —
    ровно то, чего мы избегаем."""
    assert год_прорыва(МЕЙНСТРИМ, as_of=2026) is None


def test_у_молодого_термина_нет_базы_для_сравнения():
    """Ему прорыв не нужен: обычный расчёт взлёта и так даёт верный год."""
    assert год_прорыва(МОЛОДОЙ, as_of=2026) is None


def test_на_срезе_прошлого_прорыва_ещё_не_видно():
    """Бэктест не подсматривает: в 2021 скачка SSM ещё не было."""
    assert год_прорыва(SSM, as_of=2021) is None


def test_пустой_ряд_не_ломает_расчёт():
    assert год_прорыва({}, as_of=2026) is None
