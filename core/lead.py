"""Опережающие и запаздывающие источники.

Измерено на данных (spikes/leadtime_probe.py): медианная фора препринтов над
журнальными статьями — 1 год. Тренд, видный только в запаздывающих источниках,
уже не зарождающийся; видный только в опережающих — гипотеза с высокой
неопределённостью. Нужный заказчику сигнал живёт на пересечении.

Веса умышленно мягкие. Это поправка на скорость публикации, а не утверждение,
что препринт в полтора раза важнее статьи: агрессивные веса вытащат наверх
сырые направления без подтверждения.
"""
ВЕСА_ИСТОЧНИКОВ = {
    "model": 1.6,      # HuggingFace: архитектура появляется раньше публикации
    "repo": 1.5,
    "preprint": 1.4,   # измеренная фора: медиана 1 год
    "article": 1.0,
    "patent": 0.9,     # запаздывающий, но признак коммерциализации
    "report": 0.8,
}

ПОРОГ_ВЗЛЁТА = 10
ДОЛЯ_ПИКА = 0.10


def вес_источника(doc_type: str) -> float:
    return ВЕСА_ИСТОЧНИКОВ.get(doc_type, 1.0)


def _взлёт(counts: dict[int, int]) -> int | None:
    if not counts:
        return None
    пик = max(counts.values())
    for y in sorted(counts):
        if counts[y] >= max(ПОРОГ_ВЗЛЁТА, ДОЛЯ_ПИКА * пик):
            return y
    return None


def лаг_препринтов(counts_preprint: dict[int, int],
                   counts_article: dict[int, int]) -> int | None:
    """На сколько лет препринты опередили журналы по году взлёта."""
    p, a = _взлёт(counts_preprint), _взлёт(counts_article)
    return (a - p) if (p is not None and a is not None) else None


def sql_вес() -> str:
    """Выражение CASE для взвешивания в SQL.

    Собирается из того же словаря, что и вес_источника, чтобы веса не
    разъехались между питоном и запросом.
    """
    ветви = " ".join(f"WHEN '{т}' THEN {в}" for т, в in ВЕСА_ИСТОЧНИКОВ.items())
    return f"CASE w.doc_type {ветви} ELSE 1.0 END"
