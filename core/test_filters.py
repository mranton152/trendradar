from core.filters import причина_отказа

ХОРОШИЙ = {"counts_recent": 500, "age": 3, "active_years": 5, "last_year_share": 0.35}


def test_нормальный_кандидат_проходит():
    assert причина_отказа(ХОРОШИЙ, n_countries=40) is None


def test_пакетная_заливка_отсекается():
    """Реальный случай: термин lynching tree занимал 1-е место в ТОП-15 по ИИ.

    1314 «публикаций» 2026 года, ноль стран, ноль в предыдущие годы —
    это пакетная заливка метаданных, а не тренд.
    """
    заливка = {**ХОРОШИЙ, "last_year_share": 1.0, "active_years": 1}
    assert причина_отказа(заливка, n_countries=0) is not None


def test_одна_лаборатория_ещё_не_тренд():
    assert причина_отказа(ХОРОШИЙ, n_countries=2) == "нет географического распространения"


def test_давно_известная_тема_отсекается():
    assert причина_отказа({**ХОРОШИЙ, "age": 20}, 40) == "слишком старый термин"


def test_мало_доказательств():
    assert причина_отказа({**ХОРОШИЙ, "counts_recent": 3}, 40) == "мало данных"


def test_взрывной_международный_рост_это_не_заливка():
    """Настоящий случай: vision transformer на срезе 2021. Статья ViT вышла
    в конце 2020, поэтому почти вся активность пришлась на один год — по доле
    последнего года он неотличим от пакетной заливки. Отличает география:
    у ViT 14 стран, у заливки lynching tree их было ноль.
    """
    взрыв = {**ХОРОШИЙ, "last_year_share": 0.85}
    assert причина_отказа(взрыв, n_countries=14) is None
    assert причина_отказа(взрыв, n_countries=2) == "разовый вброс данных"


def test_заливка_с_нулём_стран_по_прежнему_отсекается():
    заливка = {**ХОРОШИЙ, "last_year_share": 1.0}
    assert причина_отказа(заливка, n_countries=0) == "разовый вброс данных"
