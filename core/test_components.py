from core.components import components, pct_rank


def test_год_взлёта_а_не_первого_упоминания():
    """Единичные срабатывания 20-летней давности не должны считаться началом.

    В корпусе из 34 млн работ почти у любого термина найдутся омонимы и ошибки
    метаданных. Взлёт = выход на 10% собственного пика.
    """
    counts = {2005: 1, 2006: 2, 2019: 40, 2020: 120, 2021: 300}
    norm = dict.fromkeys(range(2017, 2022), 1000.0)
    c = components(counts, norm, as_of=2021)
    assert c["takeoff_year"] == 2019
    assert c["age"] == 2


def test_растущий_ряд_даёт_положительный_рост():
    counts = {2017: 10, 2018: 20, 2019: 40, 2020: 80, 2021: 160}
    norm = dict.fromkeys(range(2017, 2022), 1000.0)
    assert components(counts, norm, as_of=2021)["growth"] > 0


def test_ускорение_отличает_разгон_от_ровного_роста():
    norm = dict.fromkeys(range(2017, 2022), 1000.0)
    ровный = {2017: 10, 2018: 20, 2019: 40, 2020: 80, 2021: 160}
    разгон = {2017: 10, 2018: 11, 2019: 13, 2020: 60, 2021: 300}
    assert (components(разгон, norm, 2021)["accel"]
            > components(ровный, norm, 2021)["accel"])


def test_разовый_вброс_виден_по_доле_последнего_года():
    counts = {2021: 1314}
    norm = dict.fromkeys(range(2017, 2022), 1000.0)
    assert components(counts, norm, 2021)["last_year_share"] == 1.0


def test_перцентильный_ранг_устойчив_к_выбросу():
    assert pct_rank([1.0, 2.0, 3.0, 1000.0]) == [0.0, 1 / 3, 2 / 3, 1.0]


def test_совпадающие_значения_получают_одинаковый_ранг():
    """Иначе порядок в списке произвольно решает, кто «новее» при равном возрасте."""
    assert pct_rank([5.0, 5.0]) == [0.5, 0.5]
    assert pct_rank([1.0, 7.0, 7.0, 9.0]) == [0.0, 0.5, 0.5, 1.0]


def test_пустой_список_не_ломает_ранжирование():
    assert pct_rank([]) == []


# --- омонимия: у термина бывает прошлая жизнь под тем же названием ---

ТЁЗКА = {2003: 40, 2004: 55, 2005: 60, 2006: 30,   # физика диффузии
         2019: 20, 2020: 90, 2021: 300}            # генеративные модели
НОРМА = dict.fromkeys(range(2015, 2022), 1000.0)


def test_взлёт_считается_по_нынешней_жизни_термина():
    """Без этого takeoff = 2003, возраст 18 лет, и фильтр выбрасывает тренд
    как «слишком старый» — теряется ровно тот сигнал, ради которого всё."""
    c = components(ТЁЗКА, НОРМА, as_of=2021)
    assert c["takeoff_year"] == 2020
    assert c["age"] == 1


def test_первое_упоминание_тоже_из_нынешней_жизни():
    """Показывать пользователю 2003 как год рождения технологии — обман."""
    assert components(ТЁЗКА, НОРМА, as_of=2021)["first_mention"] == 2019


def test_прошлая_жизнь_помечается_флагом():
    assert components(ТЁЗКА, НОРМА, as_of=2021)["homonym_suspected"] is True
    ровный = {2018: 10, 2019: 20, 2020: 40, 2021: 80}
    assert components(ровный, НОРМА, as_of=2021)["homonym_suspected"] is False


def test_на_срезе_прошлого_берётся_сегмент_того_времени():
    """Бэктест не должен подсматривать: в 2005 нынешней жизни ещё не было."""
    c = components(ТЁЗКА, НОРМА, as_of=2005)
    assert c["takeoff_year"] == 2003


def test_излом_тренда_переопределяет_год_взлёта():
    """Настоящий ряд 'state space model' в домене ИИ (OpenAlex, 09.09.2026).
    Теория управления даёт непрерывный фон с 2000-х, Mamba — скачок в 2025.
    Без учёта излома взлёт = 2005, возраст 21, и термин выбрасывается фильтром.
    """
    ssm = {2005: 179, 2010: 280, 2014: 354, 2015: 344, 2016: 364, 2017: 374,
           2018: 400, 2019: 445, 2020: 502, 2021: 491, 2022: 423, 2023: 475,
           2024: 534, 2025: 1166, 2026: 1349}
    норма = dict.fromkeys(range(2020, 2027), 1000.0)
    c = components(ssm, норма, as_of=2026)
    assert c["takeoff_year"] == 2025
    assert c["age"] == 1
    assert c["homonym_suspected"] is True


def test_ровный_мейнстрим_не_молодеет_от_излома():
    """Иначе метод начнёт вытаскивать наверх давно известное."""
    ровный = {y: 1000 + (y - 2014) * 120 for y in range(2014, 2027)}
    норма = dict.fromkeys(range(2020, 2027), 1000.0)
    c = components(ровный, норма, as_of=2026)
    assert c["age"] > 8       # остаётся старым и будет отсеян фильтром
    assert c["homonym_suspected"] is False
