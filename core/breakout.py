"""Излом собственного тренда термина.

Разделение жизней термина по разрыву (core/homonym.py) ловит только те случаи,
когда старая тема заглохла. Измерено на живых рядах OpenAlex: у самых важных
для нас терминов старый смысл никуда не делся и публикуется непрерывно.

    state space model  2000: 96 ... 2024: 534, 2025: 1166, 2026: 1349
    diffusion model    2000: 30 ... 2022: 209, 2023: 502, 2024: 1452

Теория управления и физика диффузии дают ровный фон, а Mamba и генеративные
модели — скачок относительно этого фона. Разрыва нет, есть излом.

Без учёта излома год взлёта «state space model» внутри домена ИИ равен 2005,
возраст 21 год, и структурный фильтр выбрасывает термин как давно известный.
При этом SSM/Mamba стоит в нашем же эталонном списке того, что метод обязан
находить, — то есть метод проваливал собственную проверку.

Это по-прежнему эвристика по форме ряда. Настоящее разрешение смысла требует
эмбеддингов контекста; когда появятся кластеры, излом станет подстраховкой.
"""

МНОЖИТЕЛЬ = 2.5        # во сколько раз надо превысить свой же многолетний уровень
ОКНО_ПОИСКА = 8        # столько лет назад ищем прорыв (совпадает с MAX_AGE)
ОКНО_БАЗЫ = 5          # столько лет до окна поиска берём за базовый уровень
МИН_БАЗА = 20          # ниже этого базы нет: термин молодой, прорыв не нужен


def _медиана(значения: list[int]) -> float:
    if not значения:
        return 0.0
    ряд = sorted(значения)
    n = len(ряд)
    середина = n // 2
    return float(ряд[середина] if n % 2 else (ряд[середина - 1] + ряд[середина]) / 2)


def базовый_уровень(counts: dict[int, int], as_of: int) -> float:
    """Многолетний уровень термина до окна поиска — фон его старой жизни."""
    начало = as_of - ОКНО_ПОИСКА - ОКНО_БАЗЫ
    конец = as_of - ОКНО_ПОИСКА - 1
    return _медиана([counts.get(y, 0) for y in range(начало, конец + 1)])


def год_прорыва(counts: dict[int, int], as_of: int,
                множитель: float = МНОЖИТЕЛЬ) -> int | None:
    """Первый год, когда термин превысил свой же фон в `множитель` раз.

    Возвращает None, если фона нет (термин молодой — обычный расчёт взлёта
    и так верен) или если превышения не случилось (термин растёт ровно,
    то есть второй жизни у него нет и вытаскивать его наверх не надо).
    """
    if not counts:
        return None
    база = базовый_уровень(counts, as_of)
    if база < МИН_БАЗА:
        return None
