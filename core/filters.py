"""Структурные фильтры — антифрод сигналов.

Пороги найдены эмпирически, каждый ловил конкретный мусор в реальных прогонах.
Порядок проверок — от дешёвых к дорогим.
"""

ПОРОГИ = {
    "MAX_AGE": 8,               # лет с года взлёта: старше — не зарождающийся
    "MIN_EVIDENCE": 20,         # документов в окне: меньше — статистический шум
    "MIN_COUNTRIES": 5,         # тема одной лаборатории ещё не тренд
    "MIN_ACTIVE_YEARS": 3,      # нужен устойчивый рост, а не всплеск одного года
    "MAX_LAST_YEAR_SHARE": 0.80,  # >80% активности в одном году — подозрительно
    "MIN_COUNTRIES_ДЛЯ_ВСПЛЕСКА": 10,  # ...но если стран много, это не вброс
    "MAX_MATURITY_PCT": 0.90,   # верхний дециль по частоте = уже мейнстрим
}


# Пороги уезжают в интерфейс через /api/v1/methodology, а MAX_LAST_YEAR_SHARE = 0.8
# аналитику банка ничего не говорит. Здесь human-читаемые подписи и главное —
# какой именно мусор каждый порог ловит: это и есть содержание слайда
# «как мы боремся с ложными сигналами».
ОПИСАНИЯ_ПОРОГОВ = {
    "MAX_AGE": ("Возраст: не старше 8 лет с года взлёта. "
                "Отсекает давно известные темы."),
    "MIN_EVIDENCE": ("Объём доказательств: минимум 20 публикаций в окне. "
                     "Отсекает статистический шум."),
    "MIN_COUNTRIES": ("География: минимум 5 стран. "
                      "Тема одной лаборатории — ещё не тренд."),
    "MIN_ACTIVE_YEARS": ("Устойчивость: активность минимум в 3 года из окна. "
                         "Отсекает всплеск одного года."),
    "MAX_LAST_YEAR_SHARE": ("Доля последнего года: не выше 80%. "
                            "Признак пакетной заливки метаданных."),
    "MIN_COUNTRIES_ДЛЯ_ВСПЛЕСКА": ("...но если стран больше 10, это настоящий "
                                   "взрывной рост, а не заливка."),
    "MAX_MATURITY_PCT": ("Зрелость: не верхний дециль по частоте. "
                         "Отсекает то, что уже стало мейнстримом."),
}


def причина_отказа(comp: dict, n_countries: int) -> str | None:
    """Возвращает текст причины или None, если кандидат прошёл.

    Причины копим и печатаем сводкой: по ним видно, что именно отсеивается,
    и это же идёт на слайд «как мы боремся с ложными сигналами».
    """
    if comp["counts_recent"] < ПОРОГИ["MIN_EVIDENCE"]:
        return "мало данных"
    if comp["age"] > ПОРОГИ["MAX_AGE"]:
        return "слишком старый термин"
    if comp["active_years"] < ПОРОГИ["MIN_ACTIVE_YEARS"]:
        return "всплеск одного года"
    # Доля последнего года сама по себе не улика: у настоящего взрывного роста
    # она такая же. Измерено на срезе 2021: vision transformer имел 14 стран
    # и отсеивался как заливка, тогда как у настоящей заливки (lynching tree,
    # 1314 «публикаций» одного года) стран было ноль. Разделяет их география.
    if (comp["last_year_share"] > ПОРОГИ["MAX_LAST_YEAR_SHARE"]
            and n_countries < ПОРОГИ["MIN_COUNTRIES_ДЛЯ_ВСПЛЕСКА"]):
        return "разовый вброс данных"
    if n_countries < ПОРОГИ["MIN_COUNTRIES"]:
        return "нет географического распространения"
    return None
