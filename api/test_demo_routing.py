"""Широкий ИИ-запрос ведёт в индекс, узкий — в живой сбор; заголовок человекочитаемый."""
from api.routes.live import индекс_для, не_тема


def test_широкий_ии_запрос_ведёт_в_индекс():
    домены = ["golden", "live-abc"]
    assert индекс_для("технологии в ИИ", домены) == "golden"
    assert индекс_для("Искусственный интеллект", домены) == "golden"
    assert индекс_для("AI trends", домены) == "golden"


def test_узкий_запрос_идёт_в_живой_сбор():
    assert индекс_для("кибербезопасность ИИ", ["golden"]) is None
    assert индекс_для("квантовые сенсоры", ["golden"]) is None


def test_без_индекса_ии_живой_сбор():
    assert индекс_для("технологии в ИИ", ["live-abc"]) is None


def test_клавиатурный_набор_не_тема():
    for q in ("ывапролд", "qwertyuiop", "йцукенг", "asdfgh", "x", "   "):
        assert не_тема(q), q


def test_настоящие_запросы_проходят():
    for q in ("нейроинтерфейсы", "агентные платежи", "технологии в ИИ", "квантовые сенсоры",
              "слабые сигналы в области робототехники", "финтех и платежи", "AI trends",
              "твердотельные батареи", "федеративное обучение в банках", "6G", "5G", "ИИ"):
        assert not не_тема(q), q
